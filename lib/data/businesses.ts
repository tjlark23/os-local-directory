// Helper to generate rating breakdown from total reviews
const generateRatingBreakdown = (total: number, avgRating: number): Business["ratingBreakdown"] => {
  const fiveStarPercent = avgRating >= 4.8 ? 0.75 : avgRating >= 4.5 ? 0.65 : avgRating >= 4.0 ? 0.50 : 0.40
  const fourStarPercent = avgRating >= 4.5 ? 0.20 : 0.25
  const threeStarPercent = 0.10
  const remaining = 1 - fiveStarPercent - fourStarPercent - threeStarPercent

  return {
    5: Math.round(total * fiveStarPercent),
    4: Math.round(total * fourStarPercent),
    3: Math.round(total * threeStarPercent),
    2: Math.round(total * remaining * 0.6),
    1: Math.round(total * remaining * 0.4),
  }
}

